import { walk } from "@std/fs/walk";

const ASSETS_DIR = "./assets";
const OUTPUT_FILE = "./assetPaths.ts";

const IGNORED_FILES = [".gitkeep", ".DS_Store"];

function toIdentifier(path: string): string {
  const parts = path.split(/[^a-zA-Z0-9]+/);
  const camel = parts
    .map((part, index) =>
      index === 0
        ? part.toLowerCase()
        : part.charAt(0).toUpperCase() + part.slice(1).toLowerCase(),
    )
    .join("");

  // Prevent identifiers from starting with a number.
  return /^\d/.test(camel) ? `_${camel}` : camel;
}

const files: string[] = [];
for await (const entry of walk(ASSETS_DIR, { includeDirs: false })) {
  if (entry.name.endsWith(".ts")) continue;
  if (IGNORED_FILES.includes(entry.name)) continue;

  const assetPath = entry.path.replace(/^assets\//, "");
  files.push(assetPath);
}

files.sort();

const lines = files.map((path) => {
  const name = toIdentifier(path);
  return `export const ${name} = "/assets/${path}";`;
});

const header = [
  "// Auto-generated by tools/generate-assets.ts",
  "// Do not edit this file manually.",
  "",
  "// Centralized asset paths.",
  "// Place static files (images, videos, SVGs, etc.) under the `assets/`",
  "// directory, organized by the page or post that uses them.",
  "",
];

const output = `${header.join("\n")}${lines.join("\n")}\n`;

await Deno.writeTextFile(OUTPUT_FILE, output);
console.log(`Generated ${OUTPUT_FILE} with ${files.length} asset path(s).`);
